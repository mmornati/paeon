"""Write docs/configuration-reference.md from the rules schema (`paeon.rules`).

Every key of the rules file is in the schema with its type, its default and a sentence. This
turns the schema into a page, so the page cannot say something the code does not. Run it after
changing a rule: `uv run python scripts/gen_config_reference.py`. A test fails when the page is
behind (`tests/test_docs.py`), and `--check` does the same from a shell.
"""

from __future__ import annotations

import sys
import types
import typing
from pathlib import Path
from typing import Any, Literal, get_args, get_origin

from pydantic import BaseModel
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from paeon import rules

PAGE = Path(__file__).resolve().parent.parent / "docs" / "configuration-reference.md"

# The top-level sections, in the order a reader meets them, with the page that explains each.
SECTIONS: tuple[tuple[str, str], ...] = (
    ("correlation", "[How it works](how-it-works.md)"),
    ("maintenance", "[How it works](how-it-works.md)"),
    ("sources", "[Sources](sources.md)"),
    ("models", "[Configuration](configuration.md)"),
    ("triage", "[Configuration](configuration.md)"),
    ("investigation", "[Configuration](configuration.md)"),
    ("postmortems", "[Configuration](configuration.md)"),
    ("digest", "[Configuration](configuration.md)"),
    ("notifiers", "[Notifications](notifications.md)"),
    ("actions", "[Acting](acting.md)"),
    ("ui", "[The console](console.md)"),
    ("telemetry", "[Configuration](configuration.md#traces)"),
)

HEADER = """\
<!-- Generated by scripts/gen_config_reference.py from paeon/rules.py. Do not edit by hand. -->

# Configuration reference

Every key of the rules file (`PAEON_CONFIG`), with its type, its default and what it does. The
guides explain how the keys work together; this page is the complete list.

- Every key is optional unless it says **required**, and a key that is not listed here is
  refused when the file is loaded: a typing mistake stops the start instead of being ignored.
- A key ending in `_env` holds the **name** of an environment variable. The secret itself goes
  in the environment (or in the file named by `NAME_FILE`), never in the rules file.
- The executor reads the same format from its own copy of the file and uses the `actions` and
  `notifiers` sections.

The environment variables of the processes themselves are in
[Configuration](configuration.md#environment).
"""


def _models_in(annotation: Any) -> list[type[BaseModel]]:
    """The rule classes an annotation mentions, in order."""
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return [annotation]
    found: list[type[BaseModel]] = []
    for arg in get_args(annotation):
        for model in _models_in(arg):
            if model not in found:
                found.append(model)
    return found


def _type(annotation: Any) -> str:
    """An annotation in words a person who writes YAML would use."""
    if annotation is type(None):
        return ""
    origin = get_origin(annotation)
    if origin is typing.Annotated:
        return _type(get_args(annotation)[0])
    if origin is Literal:
        return " \\| ".join(f"`{value}`" for value in get_args(annotation))
    if origin in (typing.Union, types.UnionType):
        return " or ".join(text for arg in get_args(annotation) if (text := _type(arg)))
    if origin is tuple:
        return f"list of {_type(get_args(annotation)[0])}"
    if origin is dict:
        return f"map of name to {_type(get_args(annotation)[1])}"
    if isinstance(annotation, type):
        if issubclass(annotation, BaseModel):
            return "section"
        if issubclass(annotation, bool):
            return "boolean"
        if issubclass(annotation, int):
            return "integer"
        if issubclass(annotation, float):
            return "number"
        if issubclass(annotation, str) and annotation is not str:  # an enumeration
            return " \\| ".join(f"`{member.value}`" for member in annotation)  # type: ignore[attr-defined]
        if issubclass(annotation, str):
            return "text"
        if annotation.__name__ == "time":
            return "time (`HH:MM`)"
    return "text"


def _default(field: FieldInfo) -> str:
    if field.is_required():
        return "**required**"
    value = field.default
    if value is PydanticUndefined or isinstance(value, BaseModel):
        return ""  # a section with defaults of its own
    if value is None or value in ((), {}, ""):
        return ""
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, tuple):
        return "`[" + ", ".join(str(item) for item in value) + "]`"
    return f"`{value}`"


def _limits(field: FieldInfo) -> str:
    """The bounds the schema checks, in a few words."""
    low = high = None
    for meta in field.metadata:
        low = getattr(meta, "ge", None) if getattr(meta, "ge", None) is not None else low
        low = getattr(meta, "gt", None) if getattr(meta, "gt", None) is not None else low
        high = getattr(meta, "le", None) if getattr(meta, "le", None) is not None else high
    if low is not None and high is not None:
        return f" From {low:g} to {high:g}."
    if high is not None:
        return f" At most {high:g}."
    return ""


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _table(model: type[BaseModel], path: str, out: list[str], done: set[str]) -> None:
    """One section: its keys, then the sections its keys open."""
    doc = (model.__doc__ or "").strip()
    if doc:
        out += [" ".join(doc.split()), ""]
    out += ["| Key | Type | Default | What it does |", "|---|---|---|---|"]
    below: list[tuple[str, type[BaseModel]]] = []
    for name, field in model.model_fields.items():
        if name == "type" and get_origin(field.annotation) is Literal:
            continue  # the heading says it
        description = (field.description or "") + _limits(field)
        out.append(
            f"| `{name}` | {_type(field.annotation)} | {_default(field)} | {_cell(description)} |"
        )
        for nested in _models_in(field.annotation):
            below.append((name, nested))
    out.append("")
    for name, nested in below:
        nested_path = f"{path}.{name}"
        if nested_path in done:
            continue
        done.add(nested_path)
        out += [f"### `{nested_path}`", ""]
        _table(nested, nested_path, out, done)


def render() -> str:
    out = [HEADER]
    top = rules.Rules.model_fields
    for name, guide in SECTIONS:
        field = top[name]
        out += [f"## `{name}`", "", f"{field.description} See {guide}.", ""]
        if name == "notifiers":
            out += [
                "A map of a name of yours to a channel. The `type` key says which service it"
                " is, and the other keys depend on it. A stage sends to the channels its"
                " `notify` lists.",
                "",
            ]
            for channel in _models_in(field.annotation):
                kind = get_args(channel.model_fields["type"].annotation)[0]
                out += [f"### `type: {kind}`", ""]
                _table(channel, f"notifiers.<name>({kind})", out, set())
            continue
        if name == "sources":
            out += [
                "A map of a name of yours to a monitoring service. The `type` key says which"
                " one it is, and the other keys depend on it. A source that pushes its alerts"
                " posts them to `/ingest/<name>`.",
                "",
            ]
            for source in _models_in(field.annotation):
                kind = get_args(source.model_fields["type"].annotation)[0]
                out += [f"### `type: {kind}`", ""]
                _table(source, f"sources.<name>({kind})", out, set())
            continue
        models = _models_in(field.annotation)
        if get_origin(field.annotation) is dict:
            out += ["A map of a name of yours to:", ""]
        elif get_origin(field.annotation) is tuple:
            out += ["A list of:", ""]
        _table(models[0], name, out, set())
    missing = sorted(set(top) - {name for name, _ in SECTIONS})
    if missing:
        raise SystemExit(f"sections without a place in the reference: {missing}")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    page = render()
    if "--check" in sys.argv:
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page:
            print(f"{PAGE.name} is behind the schema: run scripts/gen_config_reference.py")
            return 1
        return 0
    PAGE.write_text(page, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(PAGE.parent.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
